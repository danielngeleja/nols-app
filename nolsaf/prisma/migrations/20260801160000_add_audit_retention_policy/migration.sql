-- Tiered audit retention with legal hold protection.
-- Existing evidence is classified before insert triggers begin governing new rows.

ALTER TABLE `auditlog`
  ADD COLUMN `retentionClass` VARCHAR(20) NOT NULL DEFAULT 'OPERATIONAL',
  ADD COLUMN `expiresAt` DATETIME(3) NULL,
  ADD COLUMN `legalHoldAt` DATETIME(3) NULL,
  ADD COLUMN `legalHoldReason` VARCHAR(500) NULL,
  ADD INDEX `auditlog_expiresAt_legalHoldAt_idx` (`expiresAt`, `legalHoldAt`),
  ADD INDEX `auditlog_retentionClass_expiresAt_idx` (`retentionClass`, `expiresAt`);

UPDATE `auditlog`
SET
  `retentionClass` = CASE
    WHEN UPPER(`action`) LIKE '%OTP%' OR UPPER(`entity`) LIKE 'OTP:%' THEN 'OTP'
    WHEN UPPER(`action`) REGEXP 'KYC|AML|COMPLIANCE' OR UPPER(`entity`) REGEXP 'KYC|AML|COMPLIANCE' THEN 'COMPLIANCE'
    WHEN UPPER(`action`) REGEXP 'PAYMENT|INVOICE|PAYOUT|REFUND|REVENUE|COMMISSION|LEDGER|RECEIPT|DISBURSEMENT|FX'
      OR UPPER(`entity`) REGEXP 'PAYMENT|INVOICE|PAYOUT|REFUND|REVENUE|COMMISSION|LEDGER|RECEIPT|DISBURSEMENT|FX'
      THEN 'FINANCIAL'
    WHEN UPPER(`action`) REGEXP 'CLIENT_ERROR|API_ERROR|HEALTH|OBSERVABILITY|DIAGNOSTIC'
      OR UPPER(`entity`) REGEXP 'CLIENT_ERROR|API_ERROR|HEALTH|OBSERVABILITY|DIAGNOSTIC'
      THEN 'TECHNICAL'
    WHEN UPPER(`action`) REGEXP 'LOGIN|LOGOUT|AUTH|SESSION|PASSWORD|2FA|SECURITY|ACCESS|IMPERSONAT'
      OR UPPER(`entity`) REGEXP 'LOGIN|LOGOUT|AUTH|SESSION|PASSWORD|2FA|SECURITY|ACCESS|IMPERSONAT'
      THEN 'SECURITY'
    ELSE 'OPERATIONAL'
  END;

UPDATE `auditlog`
SET `expiresAt` = CASE `retentionClass`
  WHEN 'OTP' THEN DATE_ADD(`createdAt`, INTERVAL 30 DAY)
  WHEN 'TECHNICAL' THEN DATE_ADD(`createdAt`, INTERVAL 90 DAY)
  WHEN 'FINANCIAL' THEN DATE_ADD(`createdAt`, INTERVAL 7 YEAR)
  WHEN 'COMPLIANCE' THEN DATE_ADD(`createdAt`, INTERVAL 7 YEAR)
  ELSE DATE_ADD(`createdAt`, INTERVAL 2 YEAR)
END;

